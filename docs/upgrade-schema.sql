-- Tillwise multi-outlet + feature upgrade for Supabase PostgreSQL.
-- Apply AFTER docs/schema.sql in the Supabase SQL editor.
-- This migration is additive: it does not delete existing demo data.

-- Ensure the two known outlets exist before adding outlet settings.
insert into outlets (id, name) values ('syd', 'Sydney'), ('pnh', 'Phnom Penh') on conflict (id) do nothing;

-- Authentication profiles link Supabase Auth users to Tillwise roles.
create table if not exists user_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'Cashier' check (role in ('Admin','Manager','Cashier')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists user_outlets (
  user_id uuid not null references user_profiles(id) on delete cascade,
  outlet_id text not null references outlets(id) on delete cascade,
  primary key (user_id, outlet_id)
);

-- Store configuration and explicit local currency per outlet.
alter table outlets add column if not exists currency_code text not null default 'AUD';
alter table outlets add column if not exists timezone text not null default 'Australia/Sydney';
update outlets set currency_code = 'AUD', timezone = 'Australia/Sydney' where id = 'syd';
update outlets set currency_code = 'USD', timezone = 'Asia/Phnom_Penh' where id = 'pnh';

-- Customer relationship management.
alter table customers add column if not exists date_of_birth date;
alter table customers add column if not exists preferred_contact text not null default 'email';
alter table customers add column if not exists last_contacted_at timestamptz;
alter table customers add column if not exists notes text;

create table if not exists customer_followups (
  id uuid primary key default gen_random_uuid(),
  customer_id text not null references customers(id) on delete cascade,
  outlet_id text not null references outlets(id),
  assigned_to uuid references user_profiles(id),
  due_at timestamptz not null,
  channel text not null default 'phone' check (channel in ('phone','email','sms','in_person')),
  subject text not null,
  notes text,
  status text not null default 'pending' check (status in ('pending','completed','cancelled')),
  completed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists customer_followups_due_idx on customer_followups(outlet_id, due_at) where status = 'pending';
create index if not exists customers_birthday_idx on customers(date_of_birth);

-- Supplier directory. Purchases can continue to retain their supplier text for backwards compatibility.
create table if not exists suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  contact_name text,
  email text,
  phone text,
  address text,
  website text,
  notes text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (name)
);

-- Gift cards use a non-sequential public code; only a hash is stored.
create table if not exists gift_cards (
  id uuid primary key default gen_random_uuid(),
  code_hash text not null unique,
  code_last4 text not null,
  initial_value numeric(12,2) not null check (initial_value > 0),
  balance numeric(12,2) not null check (balance >= 0),
  currency_code text not null,
  purchaser_customer_id text references customers(id),
  recipient_name text,
  recipient_email text,
  issued_outlet_id text not null references outlets(id),
  expires_at date,
  status text not null default 'active' check (status in ('active','redeemed','expired','cancelled')),
  created_by uuid references user_profiles(id),
  created_at timestamptz not null default now()
);
create table if not exists gift_card_transactions (
  id uuid primary key default gen_random_uuid(),
  gift_card_id uuid not null references gift_cards(id),
  outlet_id text not null references outlets(id),
  sale_id text references sales(id),
  transaction_type text not null check (transaction_type in ('issue','redeem','refund','adjustment')),
  amount numeric(12,2) not null,
  balance_after numeric(12,2) not null check (balance_after >= 0),
  created_by uuid references user_profiles(id),
  created_at timestamptz not null default now()
);
create index if not exists gift_card_txn_card_idx on gift_card_transactions(gift_card_id, created_at desc);

-- Layby plans are separate from special orders: instalments are scheduled and tracked individually.
create table if not exists layby_plans (
  id uuid primary key default gen_random_uuid(),
  plan_number bigint generated by default as identity unique,
  outlet_id text not null references outlets(id),
  customer_id text not null references customers(id),
  created_by uuid references user_profiles(id),
  currency_code text not null,
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  total numeric(12,2) not null check (total > 0),
  deposit_required numeric(12,2) not null default 0 check (deposit_required >= 0),
  balance numeric(12,2) not null check (balance >= 0),
  start_date date not null default current_date,
  due_date date,
  status text not null default 'active' check (status in ('active','completed','cancelled','defaulted')),
  notes text,
  created_at timestamptz not null default now()
);
create table if not exists layby_items (
  id uuid primary key default gen_random_uuid(),
  layby_id uuid not null references layby_plans(id) on delete cascade,
  product_id text references products(id),
  item_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);
create table if not exists layby_installments (
  id uuid primary key default gen_random_uuid(),
  layby_id uuid not null references layby_plans(id) on delete cascade,
  sequence_no integer not null,
  due_date date not null,
  amount_due numeric(12,2) not null check (amount_due > 0),
  amount_paid numeric(12,2) not null default 0 check (amount_paid >= 0),
  status text not null default 'due' check (status in ('due','partial','paid','late')),
  unique (layby_id, sequence_no)
);
create table if not exists layby_payments (
  id uuid primary key default gen_random_uuid(),
  layby_id uuid not null references layby_plans(id),
  installment_id uuid references layby_installments(id),
  outlet_id text not null references outlets(id),
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('Cash','Card','Bank transfer','Other')),
  reference text,
  received_by uuid references user_profiles(id),
  received_at timestamptz not null default now()
);
create index if not exists layby_due_idx on layby_installments(due_date, status);

-- Staff targets only. Commission calculations intentionally excluded.
create table if not exists staff_targets (
  id uuid primary key default gen_random_uuid(),
  staff_user_id uuid not null references user_profiles(id) on delete cascade,
  outlet_id text not null references outlets(id),
  period_start date not null,
  period_end date not null,
  target_amount numeric(12,2) not null check (target_amount >= 0),
  currency_code text not null,
  created_by uuid references user_profiles(id),
  created_at timestamptz not null default now(),
  check (period_end >= period_start),
  unique (staff_user_id, outlet_id, period_start, period_end)
);

-- Outbound email audit trail. Actual delivery is performed by a trusted server/Edge Function.
create table if not exists email_logs (
  id uuid primary key default gen_random_uuid(),
  outlet_id text not null references outlets(id),
  customer_id text references customers(id),
  document_type text not null check (document_type in ('quote','receipt')),
  document_id text not null,
  recipient_email text not null,
  subject text not null,
  status text not null default 'queued' check (status in ('queued','sent','failed')),
  provider_message_id text,
  error_message text,
  sent_by uuid references user_profiles(id),
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

-- Outlet-scoped uniqueness and query performance.
create index if not exists sales_outlet_time_idx on sales(outlet_id, t desc);
create index if not exists register_sessions_outlet_open_idx on register_sessions(outlet_id, opened_at desc) where closed_at is null;
create index if not exists purchases_supplier_idx on purchases(supplier);

-- Row-level security: administrators can access all outlets; other users need an explicit
-- user_outlets membership. The helper is SECURITY DEFINER to avoid policy recursion.
alter table user_profiles enable row level security;
alter table user_outlets enable row level security;
alter table suppliers enable row level security;
alter table customer_followups enable row level security;
alter table gift_cards enable row level security;
alter table gift_card_transactions enable row level security;
alter table layby_plans enable row level security;
alter table layby_items enable row level security;
alter table layby_installments enable row level security;
alter table layby_payments enable row level security;
alter table staff_targets enable row level security;
alter table email_logs enable row level security;

create policy "Users can read own profile" on user_profiles for select using (auth.uid() = id);
create policy "Admins can manage profiles" on user_profiles for all using (
  exists (select 1 from user_profiles p where p.id = auth.uid() and p.role = 'Admin' and p.active)
) with check (
  exists (select 1 from user_profiles p where p.id = auth.uid() and p.role = 'Admin' and p.active)
);
create policy "Users can read own outlet memberships" on user_outlets for select using (user_id = auth.uid());
create policy "Admins can manage outlet memberships" on user_outlets for all using (
  exists (select 1 from user_profiles p where p.id = auth.uid() and p.role = 'Admin' and p.active)
) with check (
  exists (select 1 from user_profiles p where p.id = auth.uid() and p.role = 'Admin' and p.active)
);

create or replace function public.tillwise_can_access_outlet(target_outlet text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from user_profiles p
    where p.id = auth.uid() and p.active and p.role = 'Admin'
  ) or exists (
    select 1 from user_outlets u
    where u.user_id = auth.uid() and u.outlet_id = target_outlet
  );
$$;

create policy "Suppliers readable by signed-in users" on suppliers for select to authenticated using (true);
create policy "Suppliers writable by managers" on suppliers for all to authenticated
  using (exists (select 1 from user_profiles p where p.id = auth.uid() and p.active and p.role in ('Admin','Manager')))
  with check (exists (select 1 from user_profiles p where p.id = auth.uid() and p.active and p.role in ('Admin','Manager')));
create policy "Followups outlet access" on customer_followups for all to authenticated
  using (public.tillwise_can_access_outlet(outlet_id)) with check (public.tillwise_can_access_outlet(outlet_id));
create policy "Gift cards outlet access" on gift_cards for all to authenticated
  using (public.tillwise_can_access_outlet(issued_outlet_id)) with check (public.tillwise_can_access_outlet(issued_outlet_id));
create policy "Gift card transactions outlet access" on gift_card_transactions for all to authenticated
  using (public.tillwise_can_access_outlet(outlet_id)) with check (public.tillwise_can_access_outlet(outlet_id));
create policy "Layby plans outlet access" on layby_plans for all to authenticated
  using (public.tillwise_can_access_outlet(outlet_id)) with check (public.tillwise_can_access_outlet(outlet_id));
create policy "Layby items parent outlet access" on layby_items for all to authenticated
  using (exists (select 1 from layby_plans p where p.id = layby_id and public.tillwise_can_access_outlet(p.outlet_id)))
  with check (exists (select 1 from layby_plans p where p.id = layby_id and public.tillwise_can_access_outlet(p.outlet_id)));
create policy "Layby installments parent outlet access" on layby_installments for all to authenticated
  using (exists (select 1 from layby_plans p where p.id = layby_id and public.tillwise_can_access_outlet(p.outlet_id)))
  with check (exists (select 1 from layby_plans p where p.id = layby_id and public.tillwise_can_access_outlet(p.outlet_id)));
create policy "Layby payments outlet access" on layby_payments for all to authenticated
  using (public.tillwise_can_access_outlet(outlet_id)) with check (public.tillwise_can_access_outlet(outlet_id));
create policy "Staff targets outlet access" on staff_targets for all to authenticated
  using (public.tillwise_can_access_outlet(outlet_id)) with check (public.tillwise_can_access_outlet(outlet_id));
create policy "Email logs outlet access" on email_logs for all to authenticated
  using (public.tillwise_can_access_outlet(outlet_id)) with check (public.tillwise_can_access_outlet(outlet_id));
